"""Generate database/002_seed.sql from the same synthetic data the in-memory demo uses.

Timestamps are emitted relative to now() so dashboards look "live" whenever the seed is applied.
This script only writes a .sql file — it never connects to a database.

    cd backend && python -m scripts.generate_seed_sql            # writes ../database/002_seed.sql
"""

from __future__ import annotations

import json
import sys
from datetime import datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.db.seed_data import build_seed  # noqa: E402
from app.models import utcnow  # noqa: E402

OUT = Path(__file__).resolve().parents[2] / "database" / "002_seed.sql"


def lit(v, base: datetime) -> str:
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, datetime):
        delta = int((v - base).total_seconds())
        sign = "+" if delta >= 0 else "-"
        return f"now() {sign} interval '{abs(delta)} seconds'"
    if isinstance(v, (dict, list)):
        return "'" + json.dumps(v, ensure_ascii=False).replace("'", "''") + "'::jsonb"
    return "'" + str(v).replace("'", "''") + "'"


def insert(table: str, cols: list[str], rows: list[list], base: datetime, conflict: str = "DO NOTHING") -> str:
    if not rows:
        return ""
    values = ",\n".join("  (" + ", ".join(lit(v, base) for v in r) + ")" for r in rows)
    return f"INSERT INTO {table} ({', '.join(cols)}) VALUES\n{values}\nON CONFLICT {conflict};\n\n"


def dump_models(items) -> list:
    return [i.model_dump() for i in items]


def main() -> None:
    base = utcnow().replace(microsecond=0)
    b = build_seed(now=base)
    parts = [
        "-- =====================================================================================\n",
        "-- Virtual Lab Manager — synthetic demo seed (generated by backend/scripts/generate_seed_sql.py)\n",
        "-- Demo password for every account: demo1234   |   Run AFTER 001_schema.sql.\n",
        "-- Idempotent: re-running skips rows that already exist (ON CONFLICT DO NOTHING).\n",
        "-- =====================================================================================\n",
        "BEGIN;\n\n",
    ]
    parts.append(insert("departments", ["id", "name", "code", "institution_name", "created_at"],
                        [[d.id, d.name, d.code, d.institution_name, d.created_at] for d in b.departments], base))
    parts.append(insert("users", ["id", "email", "password_hash", "full_name", "role", "department_id", "roll_number", "created_at"],
                        [[u.id, u.email, u.password_hash, u.full_name, u.role, u.department_id, u.roll_number, u.created_at]
                         for u in b.users], base))
    parts.append(insert("courses", ["id", "department_id", "code", "title", "semester", "faculty_id", "created_at"],
                        [[c.id, c.department_id, c.code, c.title, c.semester, c.faculty_id, c.created_at] for c in b.courses], base))
    parts.append(insert("course_enrollments", ["course_id", "student_id"], [list(e) for e in b.enrollments], base))
    parts.append(insert(
        "practicals",
        ["id", "course_id", "title", "description", "lab_type", "language", "starter_files", "test_cases", "rubric",
         "max_score", "due_at", "status", "proctored", "lockdown_mode", "seb_config_key", "seb_config_url",
         "worksheet", "created_by", "created_at", "updated_at"],
        [[p.id, p.course_id, p.title, p.description, p.lab_type, p.language, p.starter_files, dump_models(p.test_cases),
          dump_models(p.rubric), p.max_score, p.due_at, p.status, p.proctored, p.lockdown_mode, p.seb_config_key,
          p.seb_config_url, p.worksheet.model_dump() if p.worksheet else None, p.created_by, p.created_at, p.updated_at]
         for p in b.practicals], base))
    parts.append(insert("practical_drafts", ["practical_id", "student_id", "files", "updated_at"],
                        [[d.practical_id, d.student_id, d.files, d.updated_at] for d in b.drafts], base))
    parts.append(insert(
        "submissions",
        ["id", "practical_id", "student_id", "files", "status", "tests_passed", "tests_total", "test_results",
         "rubric_score", "max_score", "rubric_breakdown", "ai_feedback", "grading_model", "faculty_score",
         "faculty_comment", "integrity", "submitted_at", "graded_at", "reviewed_at"],
        [[s.id, s.practical_id, s.student_id, s.files, s.status, s.tests_passed, s.tests_total, dump_models(s.test_results),
          s.rubric_score, s.max_score, dump_models(s.rubric_breakdown), s.ai_feedback, s.grading_model, s.faculty_score,
          s.faculty_comment, s.integrity.model_dump(mode="json") if s.integrity else None, s.submitted_at, s.graded_at,
          s.reviewed_at] for s in b.submissions], base))
    parts.append(insert(
        "execution_logs",
        ["id", "practical_id", "student_id", "lab_type", "mode", "engine", "status", "files", "stdout", "stderr",
         "test_results", "tests_passed", "tests_total", "duration_ms", "created_at"],
        [[e.id, e.practical_id, e.student_id, e.lab_type, e.mode, e.engine, e.status, e.files, e.stdout, e.stderr,
          dump_models(e.test_results), e.tests_passed, e.tests_total, e.duration_ms, e.created_at] for e in b.execution_logs], base))
    parts.append(insert(
        "ai_hint_logs",
        ["id", "practical_id", "student_id", "execution_id", "focus_test", "hint_level", "question", "hint_text", "model",
         "source", "created_at"],
        [[h.id, h.practical_id, h.student_id, h.execution_id, h.focus_test, h.hint_level, h.question, h.hint_text, h.model,
          h.source, h.created_at] for h in b.hint_logs], base))
    parts.append(insert(
        "proctoring_sessions",
        ["id", "practical_id", "student_id", "baseline_files", "stats", "started_at", "last_seen_at"],
        [[x.id, x.practical_id, x.student_id, x.baseline_files, x.stats, x.started_at, x.last_seen_at]
         for x in b.proctor_sessions], base))
    parts.append(insert(
        "proctoring_events",
        ["id", "session_id", "practical_id", "student_id", "event_type", "detail", "occurred_at", "created_at"],
        [[e.id, e.session_id, e.practical_id, e.student_id, e.event_type, e.detail, e.occurred_at, e.created_at]
         for e in b.proctor_events], base))
    parts.append("COMMIT;\n")
    OUT.write_text("".join(parts), encoding="utf-8")
    print(f"wrote {OUT} ({OUT.stat().st_size // 1024} KB): {len(b.users)} users, {len(b.practicals)} practicals, "
          f"{len(b.submissions)} submissions, {len(b.execution_logs)} execution logs, {len(b.hint_logs)} hints, "
          f"{len(b.proctor_sessions)} proctoring sessions, {len(b.proctor_events)} proctoring events")


if __name__ == "__main__":
    main()
